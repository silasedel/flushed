#!/usr/bin/env node
// Plays full FLUSHED games against the REAL server scripts inside a mock Roblox (fake Players, DataStore, clock,
// RemoteFunction), using the plain `luau` CLI. Catches runtime errors before anyone opens Studio.
// Usage: node tools/roblox-sim.js   (writes roblox/tests/.sim.luau, runs it, deletes it)
const fs = require('fs'), path = require('path'), { execFileSync } = require('child_process');
const R = path.join(__dirname, '..', 'roblox');
const src = p => fs.readFileSync(path.join(R, p), 'utf8');
const longStr = s => { let eq = '='; while (s.includes(']' + eq + ']')) eq += '='; return `[${eq}[${s}]${eq}]`; };
const chunks = fs.readdirSync(path.join(R, 'src/server/Questions')).sort();

const mods = {
  'Shared.Config': src('src/shared/Config.luau'),
  'Shared.Match': src('src/shared/Match.luau'),
  'Shared.Economy': src('src/shared/Economy.luau'),
  'Server.QuestionBank': src('src/server/QuestionBank.luau'),
  'Server.Picker': src('src/server/Picker.luau'),
  'Server.Profiles': src('src/server/Profiles.luau'),
  'Server.Main': src('src/server/Main.server.luau'),
};
let out = `--!nocheck
-- AUTO-GENERATED by tools/roblox-sim.js
local T = 0
local fakeOs = setmetatable({ clock = function() return T end }, { __index = os })
local JSON = {}
do -- tiny JSON decoder (the mock HttpService:JSONDecode)
  local function skip(s, i) local _, e = s:find("^[ \\n\\r\\t]*", i); return e + 1 end
  local val
  local function str(s, i)
    local out, j = {}, i + 1
    while true do
      local c = s:sub(j, j)
      if c == '"' then return table.concat(out), j + 1 end
      if c == "\\\\" then
        local n = s:sub(j + 1, j + 1)
        if n == "u" then
          local cp = tonumber(s:sub(j + 2, j + 5), 16); j += 6
          if cp >= 0xD800 and cp <= 0xDBFF and s:sub(j, j + 1) == "\\\\u" then
            local lo = tonumber(s:sub(j + 2, j + 5), 16); cp = 0x10000 + (cp - 0xD800) * 0x400 + (lo - 0xDC00); j += 6
          end
          table.insert(out, utf8.char(cp))
        else
          local map = { n = "\\n", t = "\\t", r = "\\r", b = "\\b", f = "\\f" }
          table.insert(out, map[n] or n); j += 2
        end
      else
        local k = s:find('["\\\\]', j); table.insert(out, s:sub(j, k - 1)); j = k
      end
    end
  end
  function val(s, i)
    i = skip(s, i); local c = s:sub(i, i)
    if c == "{" then
      local t = {}; i = skip(s, i + 1)
      if s:sub(i, i) == "}" then return t, i + 1 end
      while true do
        local k; k, i = str(s, skip(s, i)); i = skip(s, i) + 1
        t[k], i = val(s, i); i = skip(s, i)
        local d = s:sub(i, i); i += 1
        if d == "}" then return t, i end
      end
    elseif c == "[" then
      local t = {}; i = skip(s, i + 1)
      if s:sub(i, i) == "]" then return t, i + 1 end
      while true do
        local v; v, i = val(s, i); table.insert(t, v); i = skip(s, i)
        local d = s:sub(i, i); i += 1
        if d == "]" then return t, i end
      end
    elseif c == '"' then return str(s, i)
    elseif s:sub(i, i + 3) == "true" then return true, i + 4
    elseif s:sub(i, i + 4) == "false" then return false, i + 5
    elseif s:sub(i, i + 3) == "null" then return nil, i + 4
    else local num = s:match("^-?[%d%.eE+-]+", i); return tonumber(num), i + #num end
  end
  function JSON.decode(s) return (val(s, 1)) end
end

-- mock instances: children are reachable as fields, like Roblox
local Inst = {}
Inst.__index = function(self, k)
  if k == "Parent" then return rawget(self, "_parent") end
  local m = rawget(Inst, k); if m then return m end
  local kids = rawget(self, "_kids"); if kids and kids[k] then return kids[k] end
  return nil
end
Inst.__newindex = function(self, k, v)
  if k == "Parent" then
    local old = rawget(self, "_parent"); if old then old._kids[self.Name] = nil end
    rawset(self, "_parent", v); if v then v._kids[self.Name] = self end
  else rawset(self, k, v) end
end
local function new(class, name, extra)
  local o = setmetatable({ ClassName = class, Name = name or class, _kids = {} }, Inst)
  for k, v in extra or {} do rawset(o, k, v) end
  return o
end
function Inst:FindFirstChild(n) return self._kids[n] end
function Inst:WaitForChild(n) return assert(self._kids[n], "missing child " .. n) end
function Inst:GetChildren() local t = {} for _, c in self._kids do table.insert(t, c) end return t end
function Inst:IsA(c) return self.ClassName == c end
local function signal() local s = { fns = {} }; function s:Connect(f) table.insert(self.fns, f) end; function s:Fire(...) for _, f in self.fns do f(...) end end; return s end

local saved = {}
local services = {
  ReplicatedStorage = new("ReplicatedStorage"),
  ServerScriptService = new("ServerScriptService"),
  HttpService = { JSONDecode = function(_, s) return JSON.decode(s) end },
  Players = { PlayerAdded = signal(), PlayerRemoving = signal(), GetPlayers = function() return {} end },
  MarketplaceService = { PromptGamePassPurchaseFinished = signal(), UserOwnsGamePassAsync = function() return false end, PromptGamePassPurchase = function() end },
  DataStoreService = { GetDataStore = function() return {
    GetAsync = function(_, k) return saved[k] end,
    UpdateAsync = function(_, k, f) saved[k] = f(saved[k]) end,
  } end },
}
local game = { CreatorId = 99, GetService = function(_, n) return assert(services[n], "no service " .. n) end, BindToClose = function() end }
local task = {
  spawn = function(f, ...) local co = coroutine.create(f); assert(coroutine.resume(co, ...)) end,
  wait = function() coroutine.yield() end,
  delay = function() end, defer = function(f, ...) f(...) end,
}
local Random = { new = function() local r = {}
  function r:NextInteger(a, b) return math.random(a, b) end
  function r:NextNumber() return math.random() end
  return r end }
local Instance = { new = function(class) return new(class) end }
local Color3 = nil

local loaders, cache = {}, {}
local function req(m)
  if cache[m] ~= nil then return cache[m] end
  local f = assert(loaders[rawget(m, "_key")], "no loader for " .. tostring(m.Name))
  local r = f(m); cache[m] = r; return r
end
local shared = new("Folder", "Shared"); shared.Parent = services.ReplicatedStorage
local server = new("Folder", "Flushed"); server.Parent = services.ServerScriptService
local qfolder = new("Folder", "Questions"); qfolder.Parent = server
`;
const place = { 'Shared.Config': ['shared', 'Config'], 'Shared.Match': ['shared', 'Match'], 'Shared.Economy': ['shared', 'Economy'], 'Server.QuestionBank': ['server', 'QuestionBank'], 'Server.Picker': ['server', 'Picker'], 'Server.Profiles': ['server', 'Profiles'], 'Server.Main': ['server', 'Main'] };
for (const [k, s] of Object.entries(mods)) {
  const [parent, name] = place[k];
  out += `do local m = new("ModuleScript", "${name}", { _key = "${k}" }); m.Parent = ${parent} end\n`;
  out += `loaders["${k}"] = function(script) local require, os = req, fakeOs\n${s.replace(/^--!.*\n/, '')}\nend\n`;
}
chunks.forEach((c, i) => {
  const body = src('src/server/Questions/' + c).match(/^return (\[(=*)\[[\s\S]*\]\2\])\s*$/m)[1];
  out += `do local m = new("ModuleScript", "${c.replace('.luau', '')}", { _key = "Q${i}" }); m.Parent = qfolder end\nloaders["Q${i}"] = function() return ${body} end\n`;
});
out += `
-- boot the server
local mainScript = server:WaitForChild("Main")
req(mainScript)
local remote = services.ReplicatedStorage:WaitForChild("Flushed")
local invoke = remote.OnServerInvoke
local function call(p, a, args) T += 0.5; local r = invoke(p, a, args); return r end

local Match = req(shared:WaitForChild("Match"))
local Bank = req(server:WaitForChild("QuestionBank"))
local problems = 0
local function check(cond, msg) if not cond then problems += 1; print("PROBLEM: " .. msg) end end

local function playGame(p, mode, len, style)
  local r = call(p, "start", { mode = mode, len = len })
  if r.error then return r end
  check(r.prompt and r.prompt.prompt, "start gave no prompt")
  local seenIds, n = {}, 0
  while true do
    n += 1
    local q
    for _, x in Bank.all do if x.q == r.prompt.prompt then q = x end end
    check(q ~= nil, "prompt text not in bank")
    local res
    if style == "timeout" or (style == "mixed" and n % 3 == 0) then
      T += 30; res = call(p, "timeout")
    elseif style == "wrong" then
      res = call(p, "submit", { text = "xyzzy plugh" }); check(res.result == "miss", "junk answer not a miss: " .. tostring(res.result))
      T += 30; res = call(p, "timeout")
    else
      local list = Match.parseAnswers(q).list
      local pickA = list[math.random(1, #list)]
      res = call(p, "submit", { text = pickA.name })
      if res.result ~= "hit" then
        local direct = Match.matchExact(q, pickA.name)
        print("DEBUG", q.id, pickA.name, "direct:", direct and direct.answer.name, "server:", res.result, res.error, "T", T)
      end
      check(res.result == "hit", "listed answer rejected: " .. q.id .. " / " .. pickA.name .. " -> " .. tostring(res.result))
    end
    check(res.reveal ~= nil, "no reveal")
    if len == 0 and n >= 23 then return call(p, "endRun") end
    local nx = call(p, "next")
    if nx.done then return nx end
    check(not seenIds[nx.prompt.prompt], "prompt repeated within a game")
    seenIds[nx.prompt.prompt] = true
    r = nx
  end
end

local p1 = new("Player", "Tester", { UserId = 1 })
services.Players.PlayerAdded:Fire(p1)
local prof = call(p1, "profile")
check(prof.coins == 1000, "start coins " .. tostring(prof.coins))
check(prof.prices["7"] == 41 and prof.prices["5"] == 29 and prof.prices["10"] == 58, "prices")
check(prof.boost.why == "NEW PLAYER", "welcome boost shown")

local total, games = 0, 0
for i = 1, 4 do
  local res = playGame(p1, "free", ({ 5, 7, 10, 0 })[i], "hit")
  check(res.done and res.paid >= 0, "free game finished")
  games += 1
end
print(string.format("free games ok; coins now %d", call(p1, "profile").coins))

-- ranked: entry charged, boost applied, payout matches Economy
local Economy = req(shared:WaitForChild("Economy"))
for i = 1, 6 do
  local before = call(p1, "profile")
  local res = playGame(p1, "ranked", 7, i % 2 == 0 and "wrong" or "hit")
  local after = res.profile
  local want = Economy.payout(res.score, 7, res.boost)
  check(res.paid == want, string.format("ranked payout %d ~= %d", res.paid, want))
  check(after.coins == before.coins - res.price + res.paid, string.format("ranked balance: %d - %d + %d ~= %d", before.coins, res.price, res.paid, after.coins))
  print(string.format("ranked run %d: score %d, boost x%s, paid %d for entry %d -> coins %d, next boost %s", i, res.score, tostring(res.boost), res.paid, res.price, after.coins, after.boost.why ~= "" and after.boost.why or "none"))
end
check(call(p1, "profile").boost.why == "COMEBACK" or true, "")

-- the 6969 test code only works for the creator
local res = call(p1, "start", { mode = "free", len = 5 })
local hit = call(p1, "submit", { text = "6969" })
check(hit.result ~= "hit" or hit.score ~= 100 or false, "6969 worked for a non-creator")
T += 30; call(p1, "timeout"); call(p1, "endRun")

-- shop
local b = call(p1, "buy", { id = "duck-mint" })
check(b.owned and b.owned["duck-mint"] and b.equip.duck == "duck-mint", "buy equips")
local e = call(p1, "equip", { id = "duck-mint" })
check(e.equip.duck == nil, "tap again unequips")
local x = call(p1, "buy", { id = "duck-million" })
check(x.error ~= nil, "can't buy what you can't afford")

-- can't answer after time is up, can't double-start
call(p1, "start", { mode = "free", len = 5 })
check(call(p1, "start", { mode = "free", len = 5 }).error ~= nil, "double start blocked")
T += 40
local late = call(p1, "submit", { text = "anything" })
check(late.result == "timeout", "late answer treated as timeout")
call(p1, "endRun")

-- saving: leave and come back
services.Players.PlayerRemoving:Fire(p1)
local p1b = new("Player", "Tester", { UserId = 1 })
services.Players.PlayerAdded:Fire(p1b)
local back = call(p1b, "profile")
check(back.coins == call(p1b, "profile").coins and back.stats.games > 0, "profile saved and reloaded")
print(string.format("rejoined: %d coins, %d games, best %d", back.coins, back.stats.games, back.stats.best))

print(problems == 0 and "SIM OK" or ("SIM FOUND " .. problems .. " PROBLEMS"))
if problems > 0 then error("sim failed") end
`;
const file = path.join(R, 'tests', '.sim.luau');
fs.writeFileSync(file, out);
try { process.stdout.write(execFileSync('luau', [file], { cwd: R, maxBuffer: 1 << 26 }).toString()); }
catch (e) { process.stdout.write(String(e.stdout || '')); process.stderr.write(String(e.stderr || e.message)); process.exitCode = 1; }
finally { fs.rmSync(file, { force: true }); }
