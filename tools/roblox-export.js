#!/usr/bin/env node
// Export the question pool for the Roblox version (roblox/src/server/Questions/*.luau).
// Applies the same overrides as the web game (removed, difficulty, wording) and precomputes everything the web
// picker works out with regexes (topic group, brainrot/vague/famous/fandom flags, phrase-matching rules), so the
// Luau side never needs JS-style regexes. Each chunk is a ModuleScript returning a JSON string (decoded on the server).
// Usage: node tools/roblox-export.js
const fs = require('fs'), path = require('path'), vm = require('vm');
const M = require('../js/match.js');
const root = path.join(__dirname, '..');
const ctx = { window: {} }; ctx.window.KRILLION = { questions: [], add(l) { this.questions.push(...l); } }; ctx.KRILLION = ctx.window.KRILLION;
vm.createContext(ctx);
const qdir = path.join(root, 'data', 'questions');
const tracked = new Set(require('child_process').execSync('git ls-files data/questions', { cwd: root }).toString().split('\n').map(p => p.split('/').pop()));
for (const f of fs.readdirSync(qdir).filter(f => f.endsWith('.js') && tracked.has(f)).sort()) vm.runInContext(fs.readFileSync(path.join(qdir, f), 'utf8'), ctx);
for (const f of ['difficulty.js', 'wording.js', 'families.js', 'removed.js']) vm.runInContext(fs.readFileSync(path.join(root, 'data', f), 'utf8'), ctx);
const K = ctx.KRILLION;
const REMOVED = new Set(K.removed || []), DIFF = K.difficulty || {}, WORD = K.wording || {}, FAMILY = K.family || {};

// --- same rules as js/game.js ---
const isBrainrot = q => q.cat === 'Brainrot' || /\b(brain ?rot|gen alpha|meme|skibidi|rizz|sigma|aura|npc|ohio|gyatt|fanum)\b/i.test(q.q);
const isVague = q => /^(name|give) (something|anything|a thing|an object|an item)\b/i.test(q.q);
const isFamous = q => /\b(famous|popular|well[- ]known|notable|celebrit\w*|iconic|legendary)\b/i.test(q.q);
const isFandom = q => /\b(character|villain|cast member|episode)\b/i.test(q.q);
const kindOf = q => q.q.toLowerCase().replace(/^(name|give|list)\s+(a|an|any|one of the|one of|the|some)?\s*/, '').split(/[^a-z]+/)[0];
const TEMPLATE = /\b(model|emoji|rhymes?|synonym|in spanish|in french|compound|starts? with|beginning with|starting with|song by|team based in|in its title|in the title|in the title of|movie with|movie about|show about|movie or show|shows? with|starring|movie by|cartoon|part of|parts of|piece of)s?\b/i;
const groupOf = q => (FAMILY[q.id] ? 'f' + FAMILY[q.id] : TEMPLATE.test(q.q) ? 't:' + TEMPLATE.exec(q.q)[1].toLowerCase().replace(/s$/, '').replace(/^(start|beginning|starting) with$|^starts with$/, 'letter') : 'k:' + kindOf(q));
const ANCHOR = /\b(?:goes|go|comes|come|follows?|precedes?)\s+(after|before)\s+['"‘“]([^'"’”]+)['"’”]/i;

const out = [];
for (const q0 of K.questions) {
  if (REMOVED.has(q0.id)) continue;
  const q = { ...q0, diff: DIFF[q0.id] || q0.diff, q: WORD[q0.id] || q0.q };
  const am = ANCHOR.exec(q.q);
  out.push({
    id: q.id, q: q.q, pack: q.pack, diff: q.diff, cat: q.cat,
    group: groupOf(q),
    flags: (isBrainrot(q) ? 'b' : '') + (isVague(q) ? 'v' : '') + (isFamous(q) ? 'f' : '') + (isFandom(q) ? 'd' : ''),
    // phrase matching ("lemon gatorade" -> Lemon) is off for geography and letter prompts, same as js/match.js
    noContain: q.pack === 'geography' || /\b(starts?|starting|beginning|begins)\s+with\b/i.test(q.q) || undefined,
    anchor: am ? [am[1].toLowerCase(), M.norm(am[2])] : undefined,
    a: q.a,
  });
}
out.sort((x, y) => (x.id < y.id ? -1 : 1));

const dest = path.join(root, 'roblox', 'src', 'server', 'Questions');
fs.rmSync(dest, { recursive: true, force: true }); fs.mkdirSync(dest, { recursive: true });
const CHUNK = 150000; // characters per ModuleScript, comfortably small for Studio
let buf = [], size = 0, n = 0;
const flush = () => {
  if (!buf.length) return;
  const json = JSON.stringify(buf);
  let eq = '='; while (json.includes(']' + eq + ']')) eq += '=';
  n++;
  fs.writeFileSync(path.join(dest, `Chunk${String(n).padStart(3, '0')}.luau`), `-- AUTO-GENERATED by tools/roblox-export.js. Do not edit.\nreturn [${eq}[${json}]${eq}]\n`);
  buf = []; size = 0;
};
for (const q of out) { const s = JSON.stringify(q).length; if (size + s > CHUNK) flush(); buf.push(q); size += s; }
flush();
console.log(`exported ${out.length} prompts into ${n} chunks -> roblox/src/server/Questions/`);
