#!/usr/bin/env node
// Build roblox/tests/fixture.luau: sample prompts + typed inputs + what the WEB matcher says about each.
// roblox/tests/run.luau replays them through the Luau port and fails on any difference.
// Usage: node tools/roblox-fixture.js [every=8]
const fs = require('fs'), path = require('path');
const M = require('../js/match.js');
const root = path.join(__dirname, '..');
const every = Number(process.argv[2] || 8);
const all = [];
for (const f of fs.readdirSync(path.join(root, 'roblox/src/server/Questions')).sort()) {
  const src = fs.readFileSync(path.join(root, 'roblox/src/server/Questions', f), 'utf8');
  const m = src.match(/^return \[(=+)\[([\s\S]*)\]\1\]\s*$/m); all.push(...JSON.parse(m[2]));
}
const lua = s => '"' + String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n').replace(/\r/g, '\\r') + '"';
let seed = 12345; const rnd = () => ((seed = (seed * 1103515245 + 12345) >>> 0) / 4294967296);
const JUNK = ['banana', 'xyzzy', 'the thing', 'big', 'qwerty', 'idk', 'pizza', 'red car', 'new york', 'hello world'];
const ADJ = ['big', 'small', 'green', 'old', 'my', 'giant', 'spicy', 'new'];
const lines = ['-- AUTO-GENERATED by tools/roblox-fixture.js', 'return {'];
let cases = 0;
for (let i = 0; i < all.length; i += every) {
  const q = all[i];
  const jq = { q: q.q, pack: q.pack, a: q.a }; // the JS matcher reads q.q / q.pack for its rules
  const inputs = new Set();
  const names = q.a.map(r => String(r).split('|')).slice(0, 40);
  for (const p of names) {
    const nm = p[0].replace(/^!/, ''); inputs.add(nm); if (p[2]) inputs.add(p[2]);
    if (rnd() < 0.5 && nm.length > 4) { const k = 1 + Math.floor(rnd() * (nm.length - 2)); inputs.add(nm.slice(0, k) + nm.slice(k + 1)); }
    if (rnd() < 0.3 && nm.length > 3) inputs.add(nm.toUpperCase() + 's');
    if (rnd() < 0.3) inputs.add(ADJ[Math.floor(rnd() * ADJ.length)] + ' ' + nm.toLowerCase());
    if (rnd() < 0.15) inputs.add(nm.slice(0, 5));
  }
  for (const j of JUNK) if (rnd() < 0.4) inputs.add(j);
  const qLua = `{id=${lua(q.id)},q=${lua(q.q)},pack=${lua(q.pack)},noContain=${q.noContain ? 'true' : 'nil'},anchor=${q.anchor ? `{${lua(q.anchor[0])},${lua(q.anchor[1])}}` : 'nil'},a={${q.a.map(lua).join(',')}}}`;
  const tests = [];
  for (const inp of inputs) {
    const ex = M.matchExact(jq, inp), mc = !ex && M.matchContained(jq, inp), sg = !ex && !mc && M.suggest(jq, inp);
    const fz = M.match(jq, inp);
    const want = ex ? `E:${ex.answer.name}` : mc ? `C:${mc.answer.name}:${M.containedScore(mc.answer.score)}` : sg ? `S:${sg.answer.name}` : '-';
    tests.push(`{${lua(inp)},${lua(want)},${lua(fz ? fz.answer.name : '-')},${lua(M.norm(inp))}}`); cases++;
  }
  lines.push(`{q=${qLua},t={${tests.join(',')}}},`);
}
lines.push('}');
fs.writeFileSync(path.join(root, 'roblox/tests/fixture.luau'), lines.join('\n'));
console.log(`fixture: ${Math.ceil(all.length / every)} prompts, ${cases} typed inputs`);
