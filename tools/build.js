#!/usr/bin/env node
// Concatenates data/questions/*.js into data/questions.bundle.js (loaded by index.html).
const fs = require('fs'), path = require('path');
const TRACKED = new Set(process.env.TRACKED_ONLY ? require('child_process').execSync('git ls-files data/questions', { cwd: require('path').join(__dirname, '..') }).toString().split('\n').map(p => p.split('/').pop()) : []); // TRACKED_ONLY=1: skip files not yet committed
const dir = path.join(__dirname, '..', 'data', 'questions');
const files = fs.readdirSync(dir).filter(f => f.endsWith('.js')).sort().filter(f => !process.env.TRACKED_ONLY || TRACKED.has(f));
const out = ['// AUTO-GENERATED by tools/build.js — do not edit. Source: data/questions/*.js'];
for (const f of files) out.push(`// ---- ${f}\n` + fs.readFileSync(path.join(dir, f), 'utf8'));
fs.writeFileSync(path.join(__dirname, '..', 'data', 'questions.bundle.js'), out.join('\n'));
console.log(`bundled ${files.length} files`);

require('./families.js'); // look-alike prompt families for the picker
// Cache-bust: give every local script/stylesheet in index.html a fresh ?v= so browsers load the new version right away.
{
  const idx = path.join(__dirname, '..', 'index.html'), v = Date.now().toString(36);
  let html = fs.readFileSync(idx, 'utf8');
  html = html.replace(/((?:src|href)="(?:js|css|data)\/[^"?]+\.(?:js|css))(\?v=[^"]*)?"/g, `$1?v=${v}"`);
  fs.writeFileSync(idx, html);
}
