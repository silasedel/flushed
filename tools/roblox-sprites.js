#!/usr/bin/env node
// Export the website's pixel-art sprites (SPR in js/ocean.js) for Roblox: roblox/src/client/Sprites.luau.
// Each row of same-colored pixels becomes one "run" (x, y, length, palette index), so the Roblox client can draw
// every sprite as real pixel art out of Frames, with no image uploads needed.
// Usage: node tools/roblox-sprites.js
const fs = require('fs'), path = require('path'), vm = require('vm');
const root = path.join(__dirname, '..');
const src = fs.readFileSync(path.join(root, 'js/ocean.js'), 'utf8');
const body = src.slice(src.indexOf('const SPR = {'), src.indexOf('\n  function sprite('));
const ctx = {}; vm.createContext(ctx); vm.runInContext(body.replace('const SPR', 'SPR') + ';', ctx);
const full = h => (/^#[0-9a-f]{3}$/i.test(h) ? '#' + h.slice(1).split('').map(c => c + c).join('') : h);
const lines = ['-- AUTO-GENERATED by tools/roblox-sprites.js from js/ocean.js. Do not edit.',
  '-- name = {w, h, pal = {hex...}, runs = {x, y, len, palIndex, ...}} (x, y 0-based)', 'return {'];
let skipped = 0;
for (const [name, s] of Object.entries(ctx.SPR)) {
  const h = s.r.length, w = Math.max(...s.r.map(r => r.length));
  const pal = [], idx = {}, runs = [];
  s.r.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x]; const col = full(s.p[ch] || '');
      if (ch === '.' || !/^#[0-9a-f]{6}$/i.test(col)) { if (ch !== '.') skipped++; x++; continue; }
      let len = 1; while (x + len < row.length && row[x + len] === ch) len++;
      if (!(col in idx)) { idx[col] = pal.length + 1; pal.push(col); }
      runs.push(x, y, len, idx[col]); x += len;
    }
  });
  lines.push(`\t${name} = { w = ${w}, h = ${h}, pal = { ${pal.map(c => `"${c}"`).join(', ')} }, runs = { ${runs.join(', ')} } },`);
}
lines.push('}');
fs.writeFileSync(path.join(root, 'roblox/src/client/Sprites.luau'), lines.join('\n') + '\n');
console.log(`exported ${Object.keys(ctx.SPR).length} sprites${skipped ? ` (${skipped} pixels with unknown colors skipped)` : ''}`);
