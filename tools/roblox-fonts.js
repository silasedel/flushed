#!/usr/bin/env node
// Export the website's fonts (IBM Plex Mono 400/500/600/700 and VT323, SIL Open Font License, see roblox/fonts/)
// as glyph outlines for Roblox: roblox/src/client/FontData.luau. Curves are flattened to line segments in font
// units; TextRaster.luau fills them crisp (no anti-aliasing), the way the website's text renders on a Mac.
// Needs opentype.js (npm i opentype.js). Usage: node tools/roblox-fonts.js
const path = require('path'), fs = require('fs');
const ot = require('opentype.js');
const root = path.join(__dirname, '..');
const CHARS = [];
for (let c = 32; c <= 126; c++) CHARS.push(String.fromCharCode(c));
CHARS.push(...'·×∞é—–“”‘’→↓…%'.split(''));
const FONTS = { plex400: 'IBMPlexMono-Regular', plex500: 'IBMPlexMono-Medium', plex600: 'IBMPlexMono-SemiBold', plex700: 'IBMPlexMono-Bold', vt323: 'VT323-Regular' };
function flatten(cmds) {
  const contours = []; let cur = null, px = 0, py = 0;
  for (const c of cmds) {
    if (c.type === 'M') { cur = [Math.round(c.x), Math.round(c.y)]; contours.push(cur); px = c.x; py = c.y; }
    else if (c.type === 'L') { cur.push(Math.round(c.x), Math.round(c.y)); px = c.x; py = c.y; }
    else if (c.type === 'Q') {
      const len = Math.hypot(c.x1 - px, c.y1 - py) + Math.hypot(c.x - c.x1, c.y - c.y1);
      const n = Math.max(2, Math.min(12, Math.ceil(len / 40)));
      for (let i = 1; i <= n; i++) { const t = i / n, a = (1 - t) * (1 - t), b = 2 * (1 - t) * t, d = t * t; cur.push(Math.round(a * px + b * c.x1 + d * c.x), Math.round(a * py + b * c.y1 + d * c.y)); }
      px = c.x; py = c.y;
    } else if (c.type === 'C') {
      const n = 8;
      for (let i = 1; i <= n; i++) { const t = i / n, u = 1 - t; cur.push(Math.round(u * u * u * px + 3 * u * u * t * c.x1 + 3 * u * t * t * c.x2 + t * t * t * c.x), Math.round(u * u * u * py + 3 * u * u * t * c.y1 + 3 * u * t * t * c.y2 + t * t * t * c.y)); }
      px = c.x; py = c.y;
    }
  }
  return contours.filter(k => k.length >= 6);
}
const lines = ['-- AUTO-GENERATED by tools/roblox-fonts.js from roblox/fonts/*.ttf (SIL Open Font License 1.1). Do not edit.',
  '-- [font] = { upm, asc, desc, glyphs = { [codepoint] = { adv, contours = { {x, y, x, y, ...}, ... } } } } (font units, y up)', 'return {'];
let total = 0;
for (const [key, file] of Object.entries(FONTS)) {
  const font = ot.loadSync(path.join(root, 'roblox/fonts', file + '.ttf'));
  const t = font.tables;
  lines.push(`\t${key} = { upm = ${font.unitsPerEm}, asc = ${t.hhea.ascender}, desc = ${-t.hhea.descender}, glyphs = {`);
  for (const ch of CHARS) {
    const gi = font.charToGlyphIndex(ch); if (!gi && ch !== ' ') continue;
    const g = font.glyphs.get(gi);
    const cont = flatten(g.path.commands);
    total += cont.reduce((n, k) => n + k.length, 0);
    lines.push(`\t\t[${ch.codePointAt(0)}] = { ${g.advanceWidth}, { ${cont.map(k => '{' + k.join(',') + '}').join(', ')} } },`);
  }
  lines.push('\t} },');
}
lines.push('}');
fs.writeFileSync(path.join(root, 'roblox/src/client/FontData.luau'), lines.join('\n') + '\n');
console.log(`exported ${Object.keys(FONTS).length} fonts, ${total / 2} outline points`);
