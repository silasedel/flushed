#!/usr/bin/env node
// Groups look-alike prompts into "families": prompts whose accepted answers mostly overlap
// ("Name a country in Europe." / "Name a country that uses the euro."). The game uses at most
// one prompt per family in a game and avoids families you've played recently.
// Writes data/families.js. Run after tools/build.js (build.js calls it).
const fs = require('fs'), path = require('path');
const TRACKED = new Set(process.env.TRACKED_ONLY ? require('child_process').execSync('git ls-files data/questions', { cwd: require('path').join(__dirname, '..') }).toString().split('\n').map(p => p.split('/').pop()) : []); // TRACKED_ONLY=1: skip files not yet committed
global.window = globalThis; global.KRILLION = { qs: [], add(a) { this.qs.push(...a); } };
const dir = path.join(__dirname, '..', 'data', 'questions');
for (const f of fs.readdirSync(dir).filter(f => f.endsWith('.js')).sort().filter(f => !process.env.TRACKED_ONLY || TRACKED.has(f))) eval(fs.readFileSync(path.join(dir, f), 'utf8'));
const M = require('../js/match.js');
const qs = KRILLION.qs;
const sets = qs.map(q => new Set(q.a.map(a => M.norm(a.split('|')[0].replace(/^!/, '')))));
// index answers -> prompts so we only compare prompts that share answers
const byAns = new Map();
sets.forEach((s, i) => { for (const x of s) { if (!byAns.has(x)) byAns.set(x, []); byAns.get(x).push(i); } });
const parent = qs.map((_, i) => i);
const find = i => (parent[i] === i ? i : (parent[i] = find(parent[i])));
const SIM = 0.6, MIN = 8;
let links = 0;
for (let i = 0; i < qs.length; i++) {
  const shared = new Map();
  for (const x of sets[i]) for (const j of byAns.get(x)) if (j > i) shared.set(j, (shared.get(j) || 0) + 1);
  for (const [j, inter] of shared) {
    if (inter >= MIN && inter / Math.min(sets[i].size, sets[j].size) >= SIM) { parent[find(i)] = find(j); links++; }
  }
}
const groups = new Map();
qs.forEach((q, i) => { const r = find(i); if (!groups.has(r)) groups.set(r, []); groups.get(r).push(q.id); });
const fam = {}; let n = 0, big = 0;
for (const ids of groups.values()) { if (ids.length < 2) continue; n++; big = Math.max(big, ids.length); for (const id of ids) fam[id] = n; }
fs.writeFileSync(path.join(__dirname, '..', 'data', 'families.js'),
  '// AUTO-GENERATED by tools/families.js: look-alike prompt families (id -> family number)\nKRILLION.family = ' + JSON.stringify(fam) + ';\n');
console.log(`families: ${n} (largest ${big}), prompts in a family: ${Object.keys(fam).length}/${qs.length}`);
if (process.argv.includes('--show')) for (const ids of [...groups.values()].filter(g => g.length > 1).sort((a, b) => b.length - a.length).slice(0, 12)) console.log(ids.length, ids.slice(0, 8).map(id => qs.find(q => q.id === id).q).join(' | '));
